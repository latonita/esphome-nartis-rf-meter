#!/usr/bin/env python3
"""Independent synthetic meter frames; requires Python's cryptography package.

No captures, personal addresses or real session keys. Committed vectors allow
the C++ tests to run without Python dependencies. Regeneration must be exact.
"""
from pathlib import Path
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

KEY = bytes(range(16))
CIU = bytes.fromhex("CD 2C 12 34 56 78 50 25")
METER = bytes.fromhex("CD 2C 87 65 43 21 50 02")


def crc(data):
    value = 0
    for byte in data:
        value ^= byte << 8
        for _ in range(8):
            value = ((value << 1) ^ (0x3D65 if value & 0x8000 else 0)) & 0xFFFF
    return (value ^ 0xFFFF).to_bytes(2, "big")


def frame(kind, payload=b""):
    body = bytearray(bytes([0, kind]) + METER + bytes(3) + payload)
    body[0] = len(body) + (2 if len(body) <= 126 else 4) - 1
    if len(body) <= 126:
        return body + crc(body)
    return body[:126] + crc(body[:126]) + body[126:] + crc(body[126:])


def u64(value):
    return b"\x00\x15" + value.to_bytes(8, "big")


def reply(invoke, counter, values, normal=False):
    apdu = bytes([0xC4, 1 if normal else 3, 0xC0 | invoke])
    if not normal:
        apdu += bytes([len(values)])
    apdu += b"".join(values)
    # Exercise the optional vendor prefix and IEC wrapper too.
    plain = bytes.fromhex("0D FD F8 02 1A 00 01 00 01 00 66") + len(apdu).to_bytes(2, "big") + apdu
    aad = bytes([1, 0x29, len(plain), 0])
    counter_bytes = counter.to_bytes(4, "big")
    nonce = bytes(CIU[i] for i in (2, 3, 4, 5, 0, 1, 6, 7)) + counter_bytes
    ciphertext_tag = AESGCM(KEY).encrypt(nonce, plain, aad)
    nested = bytes.fromhex("56 78 CD 2C 50 25 02 1A") + aad + counter_bytes
    nested += ciphertext_tag[:-16] + ciphertext_tag[-16:-4]  # 12-byte GCM tag
    return frame(0x43, nested)


def main():
    ten = list(map(u64, [29331176, 19571884, 9701030, 58262, 200, 13, 0, 185, 2230, 2200]))
    clock = bytes.fromhex("00 09 0C 07 EA 0B 08 07 01 22 2F FF 80 00 00")
    six = list(map(u64, [2290, 140, 0, 910, 5000])) + [clock]
    vectors = {
        "ACK40": frame(0x40), "ACK5B": frame(0x5B),
        "NORMAL1": reply(1, 1, [u64(123)], normal=True),
        "STALE_SAME_COUNT": reply(1, 2, ten),
        "BATCH10": reply(2, 3, ten),
        "STALE_WRONG_COUNT": reply(2, 4, ten),
        "BATCH6": reply(3, 5, six),
        "NORMAL4": reply(4, 6, [u64(123)], normal=True),
        "NEXT_BATCH10": reply(5, 7, ten),
        "NEXT_BATCH6": reply(6, 8, six),
    }
    lines = ["// Generated by generate_rf_vectors.py; synthetic test data only.",
             "#pragma once", "#include <cstdint>", "#include <vector>", "namespace fixtures {"]
    for name, value in {"KEY": KEY, "CIU": CIU, "METER": METER}.items():
        lines.append(f"inline constexpr uint8_t {name}[] = {{" + ", ".join(f"0x{x:02X}" for x in value) + "};")
    for name, value in vectors.items():
        lines.append(f"inline const std::vector<uint8_t> {name}{{")
        for i in range(0, len(value), 16):
            lines.append("  " + ", ".join(f"0x{x:02X}" for x in value[i:i + 16]) + ",")
        lines.append("};")
    lines.append("}  // namespace fixtures\n")
    Path(__file__).with_name("rf_vectors.h").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
